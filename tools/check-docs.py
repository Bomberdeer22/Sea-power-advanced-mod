#!/usr/bin/env python3
"""Check that every plain-text twin is still exactly what its Markdown says.

The repository keeps a `.txt` copy of each document a player might open in Notepad. They are
generated by `tools/md2txt.py`, and the failure mode is silent: edit the Markdown, forget the twin,
and the release ships two documents that disagree. This makes that a build error instead.

    python tools/check-docs.py            # report, exit 1 when a twin is out of date
    python tools/check-docs.py --write    # regenerate every twin in place

The comparison is byte for byte, including the CRLF line endings md2txt writes, because "almost the
same file" is still a document nobody proofread.
"""

from __future__ import annotations

import argparse
import importlib.util
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent

PAIRS = [
    ("README.md", "README.txt"),
    ("INSTALL.md", "INSTALL.txt"),
    ("docs/features.md", "docs/features.txt"),
    ("docs/testing.md", "docs/testing.txt"),
    ("docs/updating.md", "docs/updating.txt"),
    ("docs/releasing.md", "docs/releasing.txt"),
]


def load_md2txt():
    spec = importlib.util.spec_from_file_location("md2txt", ROOT / "tools" / "md2txt.py")
    module = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    spec.loader.exec_module(module)
    return module


def rendered(module, source: str) -> bytes:
    text = (ROOT / source).read_text(encoding="utf-8")
    banner = module.BANNER.format(source=source)
    body = banner + "\n" + module.convert(text)
    return body.replace("\n", "\r\n").encode("utf-8")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true", help="regenerate the twins in place")
    args = parser.parse_args()

    module = load_md2txt()

    stale = []
    missing = []

    for source, twin in PAIRS:
        if not (ROOT / source).exists():
            missing.append(source)
            continue

        wanted = rendered(module, source)
        target = ROOT / twin

        if args.write:
            target.write_bytes(wanted)
            continue

        if not target.exists():
            stale.append((twin, "missing"))
            continue

        if target.read_bytes() != wanted:
            stale.append((twin, "out of date with " + source))

    if args.write:
        print(f"rewrote {len(PAIRS)} plain-text twin(s) from their Markdown")
        return 0

    if missing:
        for source in missing:
            print(f"  {source}: missing")
        return 1

    if not stale:
        print(f"clean: {len(PAIRS)} plain-text twin(s) match their Markdown")
        return 0

    for twin, why in stale:
        print(f"  {twin}: {why}")

    print("\nRun with --write to regenerate, then check the diff before committing.")
    return 1


if __name__ == "__main__":
    sys.exit(main())
